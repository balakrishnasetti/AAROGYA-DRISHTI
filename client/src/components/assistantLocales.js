export function assistantText(language, key) {
  return sharedCopy[language]?.[key] || copy[language]?.[key] || sharedCopy.en[key] || copy.en[key] || key;
}

export function detectAssistantLanguage(message, fallback = 'en') {
  const source = String(message || '');
  if (/[\u0c00-\u0c7f]/.test(source)) return 'te';
  if (/[\u0b80-\u0bff]/.test(source)) return 'ta';
  if (/[\u0c80-\u0cff]/.test(source)) return 'kn';
  if (/[\u0d00-\u0d7f]/.test(source)) return 'ml';
  if (/[\u0980-\u09ff]/.test(source)) return 'bn';
  if (/[\u0900-\u097f]/.test(source)) return fallback === 'mr' ? 'mr' : 'hi';
  return fallback;
}
